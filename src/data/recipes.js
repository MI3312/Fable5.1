export function outLabel(out, ITEMS, BLOCKS) {
  const [id, n] = out;
  if (id.startsWith('block:')) return `${n}× ${BLOCKS[Number(id.slice(6))].name}`;
  if (id === 'nanites') return `${n} Nanites`;
  if (id === 'lore') return 'A forgotten memory';
  return `${n}× ${ITEMS[id]?.name ?? id}`;
}
